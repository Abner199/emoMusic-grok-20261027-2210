def demo_photos() -> dict[str, list[str]]:
    """static/demo 里每类情绪的真人示范照片（文件名形如 05-惊-惊讶-surprise.jpg）。"""
    out: dict[str, list[str]] = {p["id"]: [] for p in POSES}
    if not DEMO_DIR.exists():
        return out
    for path in sorted(DEMO_DIR.glob("*.jpg")):
        stem = path.stem
        if not stem[:2].isdigit():
            continue
        # 05-惊-惊讶-surprise.jpg、12-惊-惊讶-surprise-b.jpg：取其中的英文情绪名
        eid = next((part for part in stem.split("-") if part in out), "")
        if eid:
            out[eid].append(f"/static/demo/{path.name}")
    # 真人照片（-d / -e，Unsplash）排在前面
    for eid in out:
        out[eid].sort(key=lambda url: (0 if url.endswith(("-d.jpg", "-e.jpg", "-f.jpg")) else 1, url))
    return out
